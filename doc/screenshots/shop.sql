CREATE TABLE CUSTOMER (
  CUST_NO      INT          NOT NULL AUTO_INCREMENT COMMENT '고객번호',
  CUST_NM      VARCHAR(50)  NOT NULL COMMENT '고객명',
  EMAIL        VARCHAR(100) NOT NULL COMMENT '이메일',
  PHONE_NO     VARCHAR(20)  NULL     COMMENT '전화번호',
  GRADE_CD     CHAR(2)      NOT NULL DEFAULT '01' COMMENT '등급코드',
  REG_DT       DATETIME     NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
  PRIMARY KEY (CUST_NO),
  UNIQUE KEY UK_CUSTOMER_EMAIL (EMAIL)
) COMMENT='고객';

CREATE TABLE CATEGORY (
  CATEGORY_ID        INT         NOT NULL COMMENT '분류ID',
  CATEGORY_NM        VARCHAR(50) NOT NULL COMMENT '분류명',
  PARENT_CATEGORY_ID INT         NULL     COMMENT '상위분류ID',
  PRIMARY KEY (CATEGORY_ID)
) COMMENT='상품분류';

CREATE TABLE PRODUCT (
  PRODUCT_ID   INT           NOT NULL AUTO_INCREMENT COMMENT '상품ID',
  CATEGORY_ID  INT           NOT NULL COMMENT '분류ID',
  PRODUCT_NM   VARCHAR(100)  NOT NULL COMMENT '상품명',
  PRICE        DECIMAL(12,0) NOT NULL DEFAULT 0 COMMENT '판매가격',
  STOCK_QTY    INT           NOT NULL DEFAULT 0 COMMENT '재고수량',
  REG_DT       DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
  PRIMARY KEY (PRODUCT_ID),
  KEY IX_PRODUCT_NM (PRODUCT_NM),
  CONSTRAINT CK_PRODUCT_PRICE CHECK (PRICE >= 0)
) COMMENT='상품';

CREATE TABLE ORDERS (
  ORDER_NO     BIGINT        NOT NULL COMMENT '주문번호',
  CUST_NO      INT           NOT NULL COMMENT '고객번호',
  ORDER_DT     DATETIME      NOT NULL COMMENT '주문일시',
  ORDER_STATUS VARCHAR(10)   NOT NULL COMMENT '주문상태',
  TOTAL_AMT    DECIMAL(12,0) NOT NULL DEFAULT 0 COMMENT '주문금액',
  PRIMARY KEY (ORDER_NO)
) COMMENT='주문';

CREATE TABLE ORDER_ITEM (
  ORDER_NO     BIGINT        NOT NULL COMMENT '주문번호',
  ITEM_SEQ     INT           NOT NULL COMMENT '항목순번',
  PRODUCT_ID   INT           NOT NULL COMMENT '상품ID',
  ORDER_QTY    INT           NOT NULL DEFAULT 1 COMMENT '주문수량',
  UNIT_PRICE   DECIMAL(12,0) NOT NULL COMMENT '단가',
  PRIMARY KEY (ORDER_NO, ITEM_SEQ)
) COMMENT='주문상품';

CREATE TABLE PAYMENT (
  PAYMENT_ID   BIGINT        NOT NULL AUTO_INCREMENT COMMENT '결제ID',
  ORDER_NO     BIGINT        NOT NULL COMMENT '주문번호',
  PAY_METHOD   VARCHAR(10)   NOT NULL COMMENT '결제수단',
  PAY_AMT      DECIMAL(12,0) NOT NULL COMMENT '결제금액',
  PAY_DT       DATETIME      NOT NULL COMMENT '결제일시',
  PRIMARY KEY (PAYMENT_ID)
) COMMENT='결제';

CREATE TABLE DELIVERY (
  DELIVERY_ID  BIGINT        NOT NULL AUTO_INCREMENT COMMENT '배송ID',
  ORDER_NO     BIGINT        NOT NULL COMMENT '주문번호',
  RECEIVER_NM  VARCHAR(50)   NOT NULL COMMENT '수령인명',
  ADDRESS      VARCHAR(200)  NOT NULL COMMENT '배송주소',
  DELIVERY_STATUS VARCHAR(10) NOT NULL COMMENT '배송상태',
  PRIMARY KEY (DELIVERY_ID)
) COMMENT='배송';

CREATE TABLE REVIEW (
  REVIEW_ID    BIGINT        NOT NULL AUTO_INCREMENT COMMENT '리뷰ID',
  PRODUCT_ID   INT           NOT NULL COMMENT '상품ID',
  CUST_NO      INT           NOT NULL COMMENT '고객번호',
  RATING       TINYINT       NOT NULL COMMENT '평점',
  CONTENT      TEXT          NULL     COMMENT '리뷰내용',
  REG_DT       DATETIME      NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '등록일시',
  PRIMARY KEY (REVIEW_ID),
  CONSTRAINT CK_REVIEW_RATING CHECK (RATING BETWEEN 1 AND 5)
) COMMENT='상품리뷰';

ALTER TABLE CATEGORY ADD CONSTRAINT FK_CATEGORY_PARENT FOREIGN KEY (PARENT_CATEGORY_ID) REFERENCES CATEGORY (CATEGORY_ID);
ALTER TABLE PRODUCT ADD CONSTRAINT FK_PRODUCT_CATEGORY FOREIGN KEY (CATEGORY_ID) REFERENCES CATEGORY (CATEGORY_ID);
ALTER TABLE ORDERS ADD CONSTRAINT FK_ORDERS_CUSTOMER FOREIGN KEY (CUST_NO) REFERENCES CUSTOMER (CUST_NO);
ALTER TABLE ORDER_ITEM ADD CONSTRAINT FK_ORDER_ITEM_ORDERS FOREIGN KEY (ORDER_NO) REFERENCES ORDERS (ORDER_NO) ON DELETE CASCADE;
ALTER TABLE ORDER_ITEM ADD CONSTRAINT FK_ORDER_ITEM_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (PRODUCT_ID);
ALTER TABLE PAYMENT ADD CONSTRAINT FK_PAYMENT_ORDERS FOREIGN KEY (ORDER_NO) REFERENCES ORDERS (ORDER_NO);
ALTER TABLE DELIVERY ADD CONSTRAINT FK_DELIVERY_ORDERS FOREIGN KEY (ORDER_NO) REFERENCES ORDERS (ORDER_NO);
ALTER TABLE REVIEW ADD CONSTRAINT FK_REVIEW_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCT (PRODUCT_ID);

CREATE VIEW V_ORDER_SUMMARY AS
SELECT O.ORDER_NO, C.CUST_NM, O.ORDER_DT, O.TOTAL_AMT
  FROM ORDERS O JOIN CUSTOMER C ON C.CUST_NO = O.CUST_NO;
