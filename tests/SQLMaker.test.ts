import { describe, expect, it } from "vitest";
import { isSingleExpression, sqlMakerManager } from "../src/sql/SQLMaker";
import type { EntityData } from "../src/types";
import { field } from "./fixtures";

const table: EntityData = {
	physicalName: "product",
	logicalName: "Product",
	keys: [field("p1", "product_id", "INT", { isPK: true, notNull: true, ai: true })],
	fields: [
		field("p2", "name", "VARCHAR(100)", { notNull: true, comment: "Product's name" }),
		field("p3", "stock", "INT", { defaultValue: 0 }),
	],
	indexes: [{ name: "ux_product_name", fields: "name,stock", unique: true }, { name: "ix_stock", fields: "stock" }],
	checks: [{ name: "ck_stock", expression: "stock >= 0" }],
};
const fk = { childTable: "order_item", childFields: "product_id", parentTable: "product", parentFields: "product_id" };

describe("SQLMaker", () => {
	it("MariaDB: AUTO_INCREMENT, inline comments, CHECK and UNIQUE index", () => {
		const sql = sqlMakerManager.getMaker("mariadb").makeTable(table);
		expect(sql).toContain("product_id    INT    NOT NULL AUTO_INCREMENT");
		expect(sql).toContain("COMMENT 'Product''s name'");
		expect(sql).toContain("DEFAULT 0");		// 0도 기본값으로 출력
		expect(sql).toContain("CONSTRAINT ck_stock CHECK (stock >= 0)");
		expect(sql).toContain("CREATE UNIQUE INDEX ux_product_name ON product (name,stock);");
		expect(sql).toContain("CREATE INDEX ix_stock ON product (stock);");
		expect(sql).toContain("COMMENT='Product'");
	});

	it("PostgreSQL: identity and COMMENT ON", () => {
		const sql = sqlMakerManager.getMaker("postgresql").makeTable(table);
		expect(sql).toContain("GENERATED BY DEFAULT AS IDENTITY");
		expect(sql).toContain("COMMENT ON TABLE product IS 'Product';");
		expect(sql).toContain("COMMENT ON COLUMN product.name IS 'Product''s name';");
		expect(sql).not.toContain("AUTO_INCREMENT");
	});

	it("referential actions by DBMS", () => {
		expect(sqlMakerManager.getMaker("mariadb").makeForeignKey("fk1", fk, "CASCADE", "SET NULL"))
			.toContain("REFERENCES product ( product_id ) ON DELETE CASCADE ON UPDATE SET NULL;");
		// Oracle은 ON UPDATE를 지원하지 않음
		const oracle = sqlMakerManager.getMaker("oracle").makeForeignKey("fk1", fk, "CASCADE", "CASCADE");
		expect(oracle).toContain("ON DELETE CASCADE");
		expect(oracle).toContain("/* ON UPDATE CASCADE is not supported */");
		expect(sqlMakerManager.getMaker("mssql").makeForeignKey("fk1", fk, "RESTRICT")).toContain("/* ON DELETE RESTRICT is not supported */");
		// NO ACTION은 기본값이므로 생략
		expect(sqlMakerManager.getMaker("postgresql").makeForeignKey("fk1", fk, "NO ACTION")).not.toContain("ON DELETE");
	});

	it("quotes unusual identifiers per DBMS", () => {
		expect(sqlMakerManager.getMaker("mariadb").id("order item")).toBe("`order item`");
		expect(sqlMakerManager.getMaker("postgresql").id('a"b')).toBe('"a""b"');
		expect(sqlMakerManager.getMaker("oracle").id("PLAIN_NAME")).toBe("PLAIN_NAME");
	});

	it("views and sequences", () => {
		const view = { id: "v1", name: "v_stock", query: "SELECT name FROM product WHERE stock > 0;" };
		expect(sqlMakerManager.getMaker("mariadb").makeView(view)).toBe("CREATE VIEW v_stock AS\nSELECT name FROM product WHERE stock > 0;\n");
		expect(sqlMakerManager.getMaker("mssql").makeView(view, true)).toContain("CREATE OR ALTER VIEW");
		expect(sqlMakerManager.getMaker("oracle").makeView(view, true)).toContain("CREATE OR REPLACE VIEW");
		// 다른 구문이 끼어들 수 없음
		expect(sqlMakerManager.getMaker("mariadb").makeView({ ...view, query: "SELECT 1; DROP TABLE product" })).toMatch(/^-- /);

		const seq = { id: "s1", name: "seq_order", start: 100, increment: 1, cycle: true };
		expect(sqlMakerManager.getMaker("postgresql").makeSequence(seq)).toBe("CREATE SEQUENCE seq_order START WITH 100 INCREMENT BY 1 CYCLE;\n");
		expect(sqlMakerManager.getMaker("mssql").makeSequence(seq)).toContain("CREATE SEQUENCE seq_order AS BIGINT START WITH 100");
	});

	it("rejects CHECK expressions that could inject statements", () => {
		expect(isSingleExpression("price >= 0 AND name <> ';'")).toBe(true);
		expect(isSingleExpression("price >= 0); DROP TABLE x; --")).toBe(false);
		expect(isSingleExpression("a > 0 -- comment")).toBe(false);
		expect(isSingleExpression("(a > 0")).toBe(false);
		const sql = sqlMakerManager.getMaker("mariadb").makeTable({ ...table, checks: [{ name: "bad", expression: "1=1); DROP TABLE product; --" }] });
		expect(sql).not.toContain("DROP TABLE");
	});

	it("ALTER statements differ by DBMS", () => {
		const oldField = field("p2", "name", "VARCHAR(100)");
		const newField = field("p2", "name", "VARCHAR(200)", { notNull: true });
		expect(sqlMakerManager.getMaker("mariadb").modifyColumn("product", oldField, newField)).toBe("ALTER TABLE product MODIFY COLUMN name    VARCHAR(200)    NOT NULL;\n");
		expect(sqlMakerManager.getMaker("oracle").modifyColumn("product", oldField, newField)).toBe("ALTER TABLE product MODIFY (name VARCHAR(200) NOT NULL);\n");
		expect(sqlMakerManager.getMaker("postgresql").modifyColumn("product", oldField, newField))
			.toBe("ALTER TABLE product ALTER COLUMN name TYPE VARCHAR(200);\nALTER TABLE product ALTER COLUMN name SET NOT NULL;\n");
		expect(sqlMakerManager.getMaker("mssql").renameColumn("product", "name", "title")).toBe("EXEC sp_rename N'product.name', N'title', N'COLUMN';\n");
		expect(sqlMakerManager.getMaker("mariadb").dropForeignKey("orders", "fk1")).toBe("ALTER TABLE orders DROP FOREIGN KEY fk1;\n");
		expect(sqlMakerManager.getMaker("oracle").dropIndex("orders", "ix1")).toBe("DROP INDEX ix1;\n");
	});
});

describe("getUsedRelationList", () => {
	it("returns relations between the selected tables only, without duplicates", () => {
		type Node = { id: string; myChildList: Set<Rel>; myParentList: Set<Rel> };
		type Rel = { id: string; parentEntity: Node; childEntity: Node };
		const node = (id: string): Node => ({ id, myChildList: new Set(), myParentList: new Set() });
		const a = node("a"), b = node("b"), c = node("c");
		const link = (id: string, parent: Node, child: Node): Rel => {
			const r = { id, parentEntity: parent, childEntity: child };
			parent.myChildList.add(r);
			child.myParentList.add(r);
			return r;
		};
		const ab = link("ab", a, b), bc = link("bc", b, c), ba = link("ba", b, a), aa = link("aa", a, a);
		const text = { id: "t1" };		// 텍스트 등 관계가 없는 다이어그램
		const result = sqlMakerManager.getUsedRelationList([a, b, text] as never);
		expect(result.map(r => r.id)).toEqual(["ab", "aa", "ba"]);
		expect(result[0]).toBe(ab);
		expect(result).toContain(ba);
		expect(result).toContain(aa);
		expect(result).not.toContain(bc);
	});
});
