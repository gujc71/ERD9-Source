import { describe, expect, it } from "vitest";
import { extractChecks, splitStatements, Sql2Json, stripSQLComments } from "../src/sql/Sql2Json";

describe("splitStatements", () => {
	it("ignores semicolons in strings and comments", () => {
		const sql = "CREATE TABLE a (x VARCHAR(10) DEFAULT 'a;b'); -- c;d\n/* e;f */ CREATE TABLE b (y INT);";
		expect(splitStatements(sql)).toEqual(["CREATE TABLE a (x VARCHAR(10) DEFAULT 'a;b')", "CREATE TABLE b (y INT)"]);
	});
	it("splits MS-SQL GO batches", () => {
		expect(splitStatements("CREATE TABLE a (x INT)\nGO\nCREATE TABLE b (y INT)\nGO")).toEqual(["CREATE TABLE a (x INT)", "CREATE TABLE b (y INT)"]);
	});
});

describe("extractChecks", () => {
	it("keeps nested parentheses and names", () => {
		expect(extractChecks("CREATE TABLE t (a INT, CONSTRAINT ck_a CHECK (a IN (1, 2)), CHECK (a > 0))", "t"))
			.toEqual([{ name: "ck_a", expression: "a IN (1, 2)" }, { name: "CK_t_2", expression: "a > 0" }]);
	});
});

describe("Sql2Json", () => {
	it("MariaDB with the SQL parser", async () => {
		const sql2json = new Sql2Json();
		await sql2json.extract(`
			CREATE TABLE board (
				board_id INT NOT NULL AUTO_INCREMENT COMMENT 'id',
				title VARCHAR(200) NOT NULL DEFAULT 'none',
				amount DECIMAL(10,2),
				PRIMARY KEY (board_id),
				UNIQUE KEY uq_title (title),
				KEY ix_amount (amount),
				CONSTRAINT ck_amount CHECK (amount >= 0)
			) COMMENT='Board';
			CREATE TABLE reply (reply_id INT PRIMARY KEY, board_id INT NOT NULL,
				CONSTRAINT fk_reply_board FOREIGN KEY (board_id) REFERENCES board (board_id) ON DELETE CASCADE ON UPDATE NO ACTION);
			CREATE UNIQUE INDEX ux_reply ON reply (board_id, reply_id);`, undefined, "mariadb");

		const board = sql2json.tableList[0];
		expect(board).toMatchObject({ physicalName: "board", logicalName: "Board" });
		expect(board.columns[0]).toMatchObject({ column: "board_id", dataType: "INT", isPK: true, notNull: true, ai: true, comment: "id" });
		expect(board.columns[1]).toMatchObject({ column: "title", dataType: "VARCHAR(200)", defaultValue: "'none'" });
		expect(board.columns[2].dataType).toBe("DECIMAL(10,2)");
		expect(board.indexes).toEqual([{ name: "uq_title", fields: "title", unique: true }, { name: "ix_amount", fields: "amount" }]);
		expect(board.checks).toEqual([{ name: "ck_amount", expression: "amount >= 0" }]);
		expect(sql2json.relationList).toEqual([{ name: "fk_reply_board", childTable: "reply", childFields: "board_id", parentTable: "board", parentFields: "board_id", onDelete: "CASCADE", onUpdate: "NO ACTION" }]);
		expect(sql2json.tableList[1].indexes).toEqual([{ name: "ux_reply", fields: "board_id,reply_id", unique: true }]);
	});

	it("PostgreSQL inline references and COMMENT ON", async () => {
		const sql2json = new Sql2Json();
		await sql2json.extract(`
			CREATE TABLE "Users" (id SERIAL PRIMARY KEY, email varchar(100) NOT NULL UNIQUE);
			CREATE TABLE posts (id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, user_id int REFERENCES "Users"(id) ON DELETE SET NULL);
			COMMENT ON TABLE posts IS 'Blog posts';
			COMMENT ON COLUMN posts.user_id IS 'Writer';`, undefined, "postgresql");

		expect(sql2json.tableList.map(t => t.physicalName)).toEqual(["Users", "posts"]);
		expect(sql2json.tableList[0].columns[1]).toMatchObject({ column: "email", uniqueKey: true, notNull: true });
		expect(sql2json.relationList[0]).toMatchObject({ childTable: "posts", childFields: "user_id", parentTable: "Users", parentFields: "id", onDelete: "SET NULL" });
		expect(sql2json.tableList[1].logicalName).toBe("Blog posts");
		expect(sql2json.tableList[1].columns[1].comment).toBe("Writer");
	});

	it("MS-SQL brackets and identity", async () => {
		const sql2json = new Sql2Json();
		await sql2json.extract("CREATE TABLE [dbo].[T1] ([id] INT IDENTITY(1,1) NOT NULL, [nm] NVARCHAR(MAX) NULL, CONSTRAINT [PK_T1] PRIMARY KEY CLUSTERED ([id] ASC))\nGO", undefined, "mssql");
		expect(sql2json.tableList[0].physicalName).toBe("T1");
		expect(sql2json.tableList[0].columns[0]).toMatchObject({ column: "id", isPK: true, ai: true });
		expect(sql2json.tableList[0].columns[1].dataType).toBe("NVARCHAR(MAX)");
	});

	it("Oracle with regular expressions", async () => {
		const sql2json = new Sql2Json();
		await sql2json.extract(`
			CREATE TABLE dept (deptno NUMBER(2) NOT NULL, dname VARCHAR2(14), CONSTRAINT pk_dept PRIMARY KEY (deptno), CONSTRAINT uq_dname UNIQUE (dname));
			CREATE TABLE emp (empno NUMBER(4) NOT NULL, deptno NUMBER(2), sal NUMBER(7,2), CONSTRAINT ck_sal CHECK (sal > 0));
			ALTER TABLE emp ADD CONSTRAINT fk_deptno FOREIGN KEY (deptno) REFERENCES dept (deptno) ON DELETE CASCADE;
			COMMENT ON TABLE emp IS 'Employee';
			CREATE SEQUENCE emp_seq START WITH 1000 INCREMENT BY 1 NOCYCLE;
			CREATE OR REPLACE VIEW v_emp AS SELECT empno, sal FROM emp`, undefined, "oracle");

		const dept = sql2json.tableList[0];
		expect(dept.columns[0]).toMatchObject({ column: "DEPTNO", isPK: true });
		expect(dept.indexes).toEqual([{ name: "UQ_DNAME", fields: "DNAME", unique: true }]);
		expect(sql2json.tableList[1].checks).toEqual([{ name: "ck_sal", expression: "sal > 0" }]);
		expect(sql2json.tableList[1].logicalName).toBe("Employee");
		expect(sql2json.relationList[0]).toMatchObject({ name: "FK_DEPTNO", childTable: "EMP", parentTable: "DEPT", onDelete: "CASCADE" });
		expect(sql2json.sequences[0]).toMatchObject({ name: "emp_seq", start: 1000, increment: 1 });
		expect(sql2json.sequences[0].cycle).toBeUndefined();
		expect(sql2json.views[0]).toMatchObject({ name: "v_emp", query: "SELECT empno, sal FROM emp" });
	});

	it("falls back to regular expressions when the parser fails", async () => {
		const sql2json = new Sql2Json();
		// 파서가 모르는 옵션이 있어도 테이블은 가져온다
		await sql2json.extract("CREATE TABLE t1 (a INT NOT NULL, PRIMARY KEY (a)) ENGINE=InnoDB WEIRD_OPTION 123", undefined, "mariadb");
		expect(sql2json.tableList[0].columns[0]).toMatchObject({ isPK: true });
	});
});

describe("stripSQLComments", () => {
	it("keeps comment markers inside string literals", () => {
		const sql = "CREATE TABLE a (url VARCHAR(100) DEFAULT 'http://x.com/a--b', c CHAR(1) DEFAULT '/*x*/'); // note\n-- line\nCOMMENT ON TABLE a IS 'it''s -- ok';";
		expect(stripSQLComments(sql, true)).toBe("CREATE TABLE a (url VARCHAR(100) DEFAULT 'http://x.com/a--b', c CHAR(1) DEFAULT '/*x*/'); \n\nCOMMENT ON TABLE a IS 'it''s -- ok';");
	});
	it("removes block comments and // only when requested", () => {
		expect(stripSQLComments("a /* x\ny */ b // c")).toBe("a   b // c");
		expect(stripSQLComments("a /* x\ny */ b // c", true)).toBe("a   b ");
	});
	it("string literal with // is imported as default value", async () => {
		const sql2json = new Sql2Json();
		await sql2json.extract(stripSQLComments("CREATE TABLE site (id INT NOT NULL, url VARCHAR(100) DEFAULT 'http://a.b' -- home\n, PRIMARY KEY (id)); // end", true));
		expect(sql2json.tableList[0].columns.map(c => c.column)).toEqual(["ID", "URL"]);
		expect(sql2json.tableList[0].columns[1].defaultValue).toBe("'HTTP://A.B'");
	});
});
